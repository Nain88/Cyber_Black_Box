# Connects the new Kali Lab Relay collector to an administrator-owned case.
# Run on Windows AFTER relay enrollment. Credentials are NOT written to disk.
param([string]$CollectorName = 'Kali Lab Relay', [string]$CaseName = 'Kali Attack Lab')
$ErrorActionPreference = 'Stop'
$base = 'http://127.0.0.1:8765/api/v1'
Write-Host 'Cloud Box case intake configuration (Windows localhost only)' -ForegroundColor Cyan
$cred = Get-Credential -Message 'Enter the Cloud Box administrator credentials'
$otp = Read-Host 'Six-digit authenticator code if MFA is enabled (press Enter to skip)'
$body = @{ username = $cred.UserName; password = $cred.GetNetworkCredential().Password; otp = $otp } | ConvertTo-Json -Compress
$session = New-Object Microsoft.PowerShell.Commands.WebRequestSession
try {
    $login = Invoke-RestMethod -Uri "$base/auth/session" -Method Post -ContentType 'application/json' -Body $body -WebSession $session
    $headers = @{ 'X-CSRF-Token' = [string]$login.csrf }
    if ($login.user.role -ne 'admin') { throw 'Use a Cloud Box administrator account.' }
    $collectors = @(Invoke-RestMethod -Uri "$base/collectors" -WebSession $session)
    $matching = @($collectors | Where-Object { $_.name -eq $CollectorName -and $_.state -eq 'ACTIVE' })
    if ($matching.Count -eq 0) { throw "No active collector named '$CollectorName'. Start-Relay.ps1 to enroll one first." }
    $collector = $matching[-1]
    $cases = @(Invoke-RestMethod -Uri "$base/cases" -WebSession $session)
    $targetCase = $cases | Where-Object { $_.title -eq $CaseName -and $_.owner_id -eq $login.user.id } | Select-Object -First 1
    if (-not $targetCase) {
        $newCase = @{ title = $CaseName; description = 'Observed traffic from a private Kali decoy, generated by approved bounded Docker lab scenarios. This is simulation-labelled evidence.'; severity = 2 } | ConvertTo-Json
        $created = Invoke-RestMethod -Uri "$base/cases" -Method Post -WebSession $session -Headers $headers -ContentType 'application/json' -Body $newCase
        $caseId = $created.id
        Write-Host "Created case: $CaseName"
    } else { $caseId = $targetCase.id; Write-Host "Using existing case: $CaseName" }
    # Preserve other existing collector settings.
    $old = $collector.configuration
    $payload = @{ paths = @($old.paths); channels = @($old.channels); poll_seconds = $(if ($old.poll_seconds) { [int]$old.poll_seconds } else { 5 }); max_file_bytes = $(if ($old.max_file_bytes) { [int]$old.max_file_bytes } else { 20971520 }); intake_case_id = [string]$caseId } | ConvertTo-Json -Depth 10
    Invoke-RestMethod -Uri "$base/collectors/$($collector.id)/configuration" -Method Put -WebSession $session -Headers $headers -ContentType 'application/json' -Body $payload | Out-Null
    Write-Host "Linked collector $($collector.id) to case $caseId" -ForegroundColor Green
    Write-Host 'Open Cloud Box > Case workspace > Kali Attack Lab. New sealed records will appear there.'
} finally {
    try { Invoke-RestMethod -Uri "$base/auth/session" -Method Delete -WebSession $session -Headers $headers | Out-Null } catch { }
    $cred = $null
}
